    private void ConfigTabela(){
        DefaultTableModel modelo = new DefaultTableModel(
        new Object[][]{},
        new String[]{"Imprimir", "Produto", "Código"}){
        
            @Override
            public Class<?> getColumnClass(int column){
                if(column == 0){
                    return Boolean.class;
                }
                return String.class;
            }
            
            @Override
            public boolean isCellEditable(int row, int column){
                return column == 0;
            }
            
        };
        
        tabelaProdutos.setModel(modelo);
    }
    
    private void preencherTabela(){
        DefaultTableModel modelo = (DefaultTableModel) tabelaProdutos.getModel();
        
        modelo.setRowCount(0);
        
        for (Produto p : produtos) {

            modelo.addRow(new Object[]{
                false,
                p.getNome(),
                p.getCodigo()
            });

        }
    }
    
    private void carregarImpressoras() {

        ImpressoraZebra impressora = new ImpressoraZebra();

        List<PrintService> impressoras = impressora.listarImpressoras();

        Impressoras.removeAllItems();

        for (PrintService ps : impressoras) {
            Impressoras.addItem(ps.getName());
        }

    }
