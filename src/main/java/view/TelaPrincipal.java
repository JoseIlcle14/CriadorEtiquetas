    private void BuscarArquivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarArquivoActionPerformed
        JFileChooser chooser = new JFileChooser();
        
        int result = chooser.showOpenDialog(this);
        if(result == JFileChooser.APPROVE_OPTION){
            File arquivo = chooser.getSelectedFile();
            
            caminho = arquivo.getAbsolutePath();
            
            caminhoArquivo.setText(caminho);
            ImportProduto produto = new ImportProduto();
            
            List<String> planilhas = produto.listarPlanilhas(caminho);
            ListaPlanilhas.removeAllItems();
            
            for(String planilha : planilhas){
                ListaPlanilhas.addItem(planilha);
            }
        }
        
        
    }//GEN-LAST:event_BuscarArquivoActionPerformed

